"""Render the API's OpenAPI schema as TypeScript, so the frontend's API types come from here.

The frontend never hand-writes an API shape: `manage.py export_ts` writes them to
`frontend/src/integrations/rpc/api.gen.ts`, and a test fails when that file is stale.

Only the JSON Schema subset pydantic emits for our `ApiSchema` models is understood.
Anything else raises instead of degrading to `unknown`, so a new construct is noticed
the first time it appears rather than after the frontend has drifted.

Optionality follows direction. A defaulted field may be left out of a request, so it is
optional on input models; the server always serialises every field, so on output models
every field is present (possibly `null`).
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from typing import Any

HEADER = (
    "// GENERATED by `python manage.py export_ts` from the backend's OpenAPI schema.\n"
    "// Do not edit: change the backend's DTOs and re-run the command."
)
_DATE_TIME = (
    "/** An ISO 8601 date-time with an offset, e.g. `2026-11-10T14:00:00Z`. */\n"
    "export type IsoDateTime = string"
)

# Keywords that only constrain or describe a value; TypeScript has nowhere to put them.
_ANNOTATIONS = frozenset(
    {
        "title",
        "description",
        "default",
        "examples",
        "format",
        "minimum",
        "maximum",
        "exclusiveMinimum",
        "exclusiveMaximum",
        "minLength",
        "maxLength",
        "pattern",
        "minItems",
        "maxItems",
    }
)
_STRUCTURE = frozenset(
    {"$ref", "allOf", "anyOf", "enum", "const", "type", "items", "prefixItems", "properties"}
)
_OBJECT_KEYWORDS = frozenset({"required", "additionalProperties"})
_PRIMITIVES = {"string": "string", "integer": "number", "number": "number", "boolean": "boolean"}
_REF_PREFIX = "#/components/schemas/"


class SchemaError(ValueError):
    """The schema uses something this generator does not translate."""


@dataclass(frozen=True, slots=True)
class Procedure:
    path: str  # "trips/plan": what the client posts to under `/rpc/`
    summary: str
    input: str | None  # schema name; None when the procedure takes no body
    output: str


def render(openapi: dict[str, Any]) -> str:
    schemas: dict[str, Any] = openapi.get("components", {}).get("schemas", {})
    procedures = procedures_of(openapi)
    inputs = _reachable(schemas, [p.input for p in procedures if p.input])

    blocks = [HEADER, _DATE_TIME]
    for name in sorted(schemas):
        blocks.append(_declaration(name, schemas[name], optional_defaults=name in inputs))
    blocks.append(_procedure_map(procedures))
    return "\n\n".join(blocks) + "\n"


def procedures_of(openapi: dict[str, Any]) -> list[Procedure]:
    """Every operation, as a procedure. Fails on anything that isn't `POST` with JSON in and out."""
    procedures = []
    for raw_path, operations in sorted(openapi.get("paths", {}).items()):
        path = raw_path.strip("/")
        if set(operations) != {"post"}:
            raise SchemaError(f"{raw_path}: procedures are POST only, got {sorted(operations)}")
        op = operations["post"]
        body = op.get("requestBody")
        input_name = _ref_name(body["content"]["application/json"]["schema"]) if body else None
        ok = {str(code): response for code, response in op.get("responses", {}).items()}.get("200")
        if ok is None:
            raise SchemaError(f"{raw_path}: no 200 response declared")
        output_name = _ref_name(ok["content"]["application/json"]["schema"])
        procedures.append(
            Procedure(path=path, summary=op.get("summary", ""), input=input_name, output=output_name)
        )
    return procedures


def _ref_name(schema: dict[str, Any]) -> str:
    ref = schema.get("$ref")
    if not isinstance(ref, str) or not ref.startswith(_REF_PREFIX):
        raise SchemaError(f"expected a reference to a named schema, got {json.dumps(schema)}")
    return ref.removeprefix(_REF_PREFIX)


def _reachable(schemas: dict[str, Any], roots: list[str]) -> set[str]:
    """The named schemas a set of roots refers to, transitively, roots included."""
    seen: set[str] = set()
    stack = list(roots)
    while stack:
        name = stack.pop()
        if name in seen:
            continue
        if name not in schemas:
            raise SchemaError(f"reference to unknown schema {name!r}")
        seen.add(name)
        stack.extend(_refs_in(schemas[name]))
    return seen


def _refs_in(node: Any) -> list[str]:
    if isinstance(node, dict):
        found = [_ref_name(node)] if "$ref" in node else []
        for value in node.values():
            found.extend(_refs_in(value))
        return found
    if isinstance(node, list):
        return [ref for item in node for ref in _refs_in(item)]
    return []


def _declaration(name: str, schema: dict[str, Any], *, optional_defaults: bool) -> str:
    doc = _doc(schema.get("description"), indent="")
    if _is_object(schema) and "properties" in schema:
        body = _object_body(schema, name, optional_defaults=optional_defaults, indent="")
        return f"{doc}export interface {name} {body}"
    return f"{doc}export type {name} = {_type(schema, name, optional_defaults=optional_defaults, indent='')}"


def _is_object(schema: dict[str, Any]) -> bool:
    return schema.get("type") == "object" or ("properties" in schema and "type" not in schema)


def _object_body(schema: dict[str, Any], where: str, *, optional_defaults: bool, indent: str) -> str:
    _check_keywords(schema, where, allowed=_ANNOTATIONS | _STRUCTURE | _OBJECT_KEYWORDS)
    extra = schema.get("additionalProperties", False)
    if extra not in (False, None):
        raise SchemaError(f"{where}: objects with extra properties are not supported")
    required = set(schema.get("required", []))
    inner = indent + "  "
    lines = []
    for key, prop in schema["properties"].items():
        mark = "?" if optional_defaults and key not in required else ""
        prop_type = _type(prop, f"{where}.{key}", optional_defaults=optional_defaults, indent=inner)
        doc = _doc(prop.get("description"), indent=inner)
        lines.append(f"{doc}{inner}{_key(key)}{mark}: {prop_type}")
    if not lines:
        return "{}"
    return "{\n" + "\n".join(lines) + f"\n{indent}}}"


def _type(schema: dict[str, Any], where: str, *, optional_defaults: bool, indent: str) -> str:
    _check_keywords(schema, where, allowed=_ANNOTATIONS | _STRUCTURE | _OBJECT_KEYWORDS)

    def sub(node: dict[str, Any], suffix: str) -> str:
        return _type(node, f"{where}{suffix}", optional_defaults=optional_defaults, indent=indent)

    if "$ref" in schema:
        return _ref_name(schema)
    if "allOf" in schema:
        parts = [_wrap(sub(part, f"[allOf {i}]")) for i, part in enumerate(schema["allOf"])]
        return " & ".join(parts)
    if "anyOf" in schema:
        parts = [_wrap(sub(part, f"[anyOf {i}]")) for i, part in enumerate(schema["anyOf"])]
        return " | ".join(_dedupe(parts))
    if "const" in schema:
        return _literal(schema["const"])
    if "enum" in schema:
        return " | ".join(_literal(value) for value in schema["enum"])

    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(sub({**schema, "type": single}, "") for single in kind)
    if kind in _PRIMITIVES:
        if kind == "string" and schema.get("format") == "date-time":
            return "IsoDateTime"
        return _PRIMITIVES[kind]
    if kind == "null":
        return "null"
    if kind == "array":
        if "prefixItems" in schema:
            items = schema["prefixItems"]
            if schema.get("minItems") != len(items) or schema.get("maxItems") != len(items):
                raise SchemaError(f"{where}: only fixed-length tuples are supported")
            return "[" + ", ".join(sub(item, f"[{i}]") for i, item in enumerate(items)) + "]"
        if "items" not in schema:
            raise SchemaError(f"{where}: array without an item type")
        return f"{_wrap(sub(schema['items'], '[]'))}[]"
    if _is_object(schema) and "properties" in schema:
        return _object_body(schema, where, optional_defaults=optional_defaults, indent=indent)
    raise SchemaError(f"{where}: no TypeScript translation for {json.dumps(schema)}")


def _check_keywords(schema: dict[str, Any], where: str, *, allowed: frozenset[str]) -> None:
    unknown = set(schema) - allowed
    if unknown:
        raise SchemaError(f"{where}: unsupported schema keyword(s) {sorted(unknown)}")


def _wrap(ts_type: str) -> str:
    """Parenthesise a top-level union or intersection so it can nest inside another type.

    Only operators at bracket depth zero count: `[number, number]` or `{ a: 'x' | 'y' }`
    are already atomic and stay as they are.
    """
    depth = 0
    for i, char in enumerate(ts_type):
        if char in "([{":
            depth += 1
        elif char in ")]}":
            depth -= 1
        elif depth == 0 and char in "|&" and ts_type[i - 1 : i] == " ":
            return f"({ts_type})"
    return ts_type


def _literal(value: Any) -> str:
    """A JSON value as a TypeScript literal, in the frontend's single-quote style."""
    if isinstance(value, str):
        return "'" + json.dumps(value)[1:-1].replace('\\"', '"').replace("'", "\\'") + "'"
    return json.dumps(value)


def _dedupe(parts: list[str]) -> list[str]:
    out: list[str] = []
    for part in parts:
        if part not in out:
            out.append(part)
    return out


def _key(name: str) -> str:
    return name if name.isidentifier() else _literal(name)


def _doc(text: str | None, *, indent: str) -> str:
    if not text:
        return ""
    lines = [line.rstrip() for line in text.strip().splitlines()]
    if len(lines) == 1:
        return f"{indent}/** {_comment_safe(lines[0])} */\n"
    body = "\n".join(f"{indent} *{' ' + _comment_safe(line) if line else ''}" for line in lines)
    return f"{indent}/**\n{body}\n{indent} */\n"


def _comment_safe(text: str) -> str:
    return text.replace("*/", "*\\/")


def _procedure_map(procedures: list[Procedure]) -> str:
    lines = []
    for p in procedures:
        shape = f"{{ input: {p.input or 'void'}; output: {p.output} }}"
        lines.append(f"{_doc(p.summary, indent='  ')}  {_literal(p.path)}: {shape}")
    body = "\n".join(lines)
    return (
        "/** Every procedure, keyed by its path under `/rpc/`. All are `POST` with a JSON body. */\n"
        f"export interface Procedures {{\n{body}\n}}\n\n"
        "export type ProcedurePath = keyof Procedures\n"
        "export type ProcedureInput<TPath extends ProcedurePath> = Procedures[TPath]['input']\n"
        "export type ProcedureOutput<TPath extends ProcedurePath> = Procedures[TPath]['output']"
    )
